// Generates lib/src/infrastructure/config/create_configs.g.dart (typed access to the server
// and common config) from the manifest's `configDefaults`.
//
//   dart run tool/gen_config_access.dart
import 'dart:io';

import 'package:create/src/manifest/manifest.dart';

String q(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

String num_(Object v) {
  if (v is double) {
    if (v.isInfinite) return v < 0 ? 'double.negativeInfinity' : 'double.infinity';
    final s = '$v';
    return s.contains('.') || s.contains('e') ? s : '$s.0';
  }
  return '$v';
}

void main() {
  final byClass = <String, List<ConfigEntry>>{};
  for (final e in configDefaults) {
    if (e.side == ConfigSide.client) continue; // client config is the client's business
    byClass.putIfAbsent(e.javaClass, () => []).add(e);
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_config_access.dart from the manifest - never hand-edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import '../../manifest/types_network.dart';")
    ..writeln("import 'config_tree.dart';")
    ..writeln("import 'config_values.dart';")
    ..writeln();

  String typeOf(ConfigEntry e) => switch (e.type) {
    ConfigValueType.boolean => 'ConfigBool',
    ConfigValueType.integer => 'ConfigInt',
    ConfigValueType.decimal => 'ConfigDouble',
    ConfigValueType.enumeration => 'ConfigEnum',
    ConfigValueType.string => 'ConfigString',
  };

  String ctor(ConfigEntry e) {
    final side = 'ConfigSide.${e.side.name}';
    final comment = '[${e.comment.map(q).join(', ')}]';
    switch (e.type) {
      case ConfigValueType.boolean:
        return "ConfigBool(${q(e.path)}, ${e.defaultValue}, $comment, $side)";
      case ConfigValueType.integer:
        final min = e.min != null ? ', min: ${e.min}' : '';
        final max = e.max != null ? ', max: ${e.max}' : '';
        // Defaults above int32 (colours) are stored as unsigned in the manifest; keep them as is.
        return "ConfigInt(${q(e.path)}, ${e.defaultValue}, $comment, $side$min$max)";
      case ConfigValueType.decimal:
        final min = e.min != null ? ', min: ${num_(e.min!.toDouble())}' : '';
        final max = e.max != null ? ', max: ${num_(e.max!.toDouble())}' : '';
        return "ConfigDouble(${q(e.path)}, ${num_((e.defaultValue as num).toDouble())}, $comment, $side$min$max)";
      case ConfigValueType.enumeration:
        final ec = e.enumClass != null ? ', enumClass: ${q(e.enumClass!)}' : '';
        return "ConfigEnum(${q(e.path)}, ${q(e.defaultValue as String)}, $comment, $side, "
            "[${e.enumValues!.map(q).join(', ')}]$ec)";
      case ConfigValueType.string:
        return "ConfigString(${q(e.path)}, ${q(e.defaultValue as String)}, $comment, $side)";
    }
  }

  // Composition of the Java config tree (field name, class), in declaration order.
  const nested = <String, List<(String, String)>>{
    'CServer': [
      ('recipes', 'CRecipes'),
      ('kinetics', 'CKinetics'),
      ('fluids', 'CFluids'),
      ('logistics', 'CLogistics'),
      ('schematics', 'CSchematics'),
      ('equipment', 'CEquipment'),
      ('trains', 'CTrains'),
    ],
    'CKinetics': [('stressValues', 'CStress')],
    'CCommon': [('worldGen', 'CWorldGen')],
  };
  for (final k in nested.keys) {
    byClass.putIfAbsent(k, () => []);
  }

  for (final cls in byClass.keys) {
    final entries = byClass[cls]!;
    if (cls == 'CStress') {
      out.writeln('/// `CStress`: the impact and capacity of every block that has one (path of the block).');
      out.writeln('final class CStress {');
      out.writeln('  /// Stress impact per RPM by block path (`shaft`).');
      out.writeln('  final Map<String, ConfigDouble> impacts = {};');
      out.writeln();
      out.writeln('  /// Stress capacity per RPM by block path (`water_wheel`).');
      out.writeln('  final Map<String, ConfigDouble> capacities = {};');
      out.writeln();
      out.writeln('  CStress(ConfigTree tree) {');
      for (final e in entries) {
        final target = e.javaField == 'impacts' ? 'impacts' : 'capacities';
        final block = e.path.substring(e.path.lastIndexOf('.') + 1);
        out.writeln("    $target[${q(block)}] = tree.add(${ctor(e)});");
      }
      out.writeln('  }');
      out.writeln('}');
      out.writeln();
      continue;
    }
    final children = nested[cls] ?? const [];
    out.writeln('/// `$cls`: ${entries.length} values${children.isEmpty ? '' : ' and ${children.length} groups'}.');
    out.writeln('final class $cls {');
    for (final e in entries) {
      out.writeln('  /// `${e.path}`${e.comment.isNotEmpty ? ': ${e.comment.where((c) => !c.startsWith('[')).join(' ')}' : ''}');
      out.writeln('  final ${typeOf(e)} ${e.javaField};');
    }
    for (final (field, type) in children) {
      out.writeln('  final $type $field;');
    }
    out.writeln();
    final inits = <String>[
      for (final e in entries) '${e.javaField} = tree.add(${ctor(e)})',
      for (final (field, type) in children) '$field = $type(tree)',
    ];
    if (inits.isEmpty) {
      out.writeln('  $cls(ConfigTree tree);');
    } else {
      out.writeln('  $cls(ConfigTree tree)');
      for (var i = 0; i < inits.length; i++) {
        out.writeln('      ${i == 0 ? ':' : ' '} ${inits[i]}${i == inits.length - 1 ? ';' : ','}');
      }
    }
    out.writeln('}');
    out.writeln();
  }
  File('lib/src/infrastructure/config/create_configs.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote ${byClass.keys.join(', ')}');
}
