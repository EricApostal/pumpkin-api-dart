bool _isRange(List<String> v) => true;

List<String> _notes(BlockRecord r) {
  final out = <String>{};
  for (final n in r.notes) {
    // keep only notes that matter for consumers
    if (n.startsWith('stats: copper collection')) continue;
    out.add(n.startsWith('!') ? n.substring(1) : n);
  }
  return out.toList();
}

