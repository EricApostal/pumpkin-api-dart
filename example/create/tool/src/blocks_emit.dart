String q(String s) {
  final e = s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$').replaceAll('\n', r'\n').replaceAll('\r', '');
  return "'$e'";
}

String d(double v) {
  if (v == v.truncateToDouble() && v.abs() < 1e12) return v.toStringAsFixed(1);
  return v.toString();
}

