// Dart source emitters for the generated manifests.
import '../../lib/src/manifest/types_network.dart';
import 'config_extract.dart';
import 'net_extract.dart';

const _header = '// GENERATED by tool/extract_network_config.dart - never hand-edit.\n'
    '// ignore_for_file: type=lint\n\n';

String q(String s) {
  final e = s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return "'$e'";
}

String _num(num v) {
  if (v is int) return '$v';
  if (v.isInfinite) return v > 0 ? 'double.infinity' : 'double.negativeInfinity';
  return '$v';
}

String emitType(NetType t) {
  final args = <String>[];
  if (t.element != null) args.add('element: ${emitType(t.element!)}');
  if (t.key != null) args.add('key: ${emitType(t.key!)}');
  if (t.value != null) args.add('value: ${emitType(t.value!)}');
  if (t.className != null) args.add('className: ${q(t.className!)}');
  if (t.maxLength != null) args.add('maxLength: ${t.maxLength}');
  if (t.nullable) args.add('nullable: true');
  if (t.fields != null) {
    args.add('fields: [${t.fields!.map((f) => 'NetField(${q(f.name)}, ${emitType(f.type)})').join(', ')}]');
  }
  return args.isEmpty ? 'NetType(NetKind.${t.kind.name})' : 'NetType(NetKind.${t.kind.name}, ${args.join(', ')})';
}

String emitNetwork(List<NetPayload> payloads) {
  final b = StringBuffer(_header);
  b.writeln("import 'types_network.dart';\n");
  b.writeln('/// Every network payload: ${payloads.length} total '
      '(${payloads.where((p) => p.direction == NetDirection.serverbound).length} serverbound, '
      '${payloads.where((p) => p.direction == NetDirection.clientbound).length} clientbound).');
  b.writeln('const networkPayloads = <NetPayload>[');
  for (final p in payloads) {
    b.writeln('  NetPayload(');
    b.writeln('    id: ${q(p.id)},');
    if (p.constant != null) b.writeln('    constant: ${q(p.constant!)},');
    b.writeln('    direction: NetDirection.${p.direction.name},');
    b.writeln('    javaClass: ${q(p.javaClass)},');
    b.writeln('    javaSource: ${q(p.javaSource)},');
    b.writeln('    verified: ${p.verified},');
    if (p.note != null) b.writeln('    note: ${q(p.note!)},');
    if (p.fields.isEmpty) {
      b.writeln('    fields: [],');
    } else {
      b.writeln('    fields: [');
      for (final f in p.fields) {
        b.writeln('      NetField(${q(f.name)}, ${emitType(f.type)}),');
      }
      b.writeln('    ],');
    }
    b.writeln('  ),');
  }
  b.writeln('];');
  return b.toString();
}

String emitConfig(List<ConfigEntry> entries) {
  final b = StringBuffer(_header);
  b.writeln("import 'types_network.dart';\n");
  b.writeln('/// All config keys with defaults (${entries.length}).');
  b.writeln('const configDefaults = <ConfigEntry>[');
  for (final e in entries) {
    final args = <String>[
      'side: ConfigSide.${e.side.name}',
      'path: ${q(e.path)}',
      'type: ConfigValueType.${e.type.name}',
      'defaultValue: ${e.defaultValue is String ? q(e.defaultValue as String) : e.defaultValue is num ? _num(e.defaultValue as num) : e.defaultValue}',
      'javaClass: ${q(e.javaClass)}',
      'javaField: ${q(e.javaField)}',
    ];
    if (e.min != null) args.add('min: ${_num(e.min!)}');
    if (e.max != null) args.add('max: ${_num(e.max!)}');
    if (e.enumClass != null) args.add('enumClass: ${q(e.enumClass!)}');
    if (e.enumValues != null) args.add('enumValues: [${e.enumValues!.map(q).join(', ')}]');
    if (e.comment.isNotEmpty) args.add('comment: [${e.comment.map(q).join(', ')}]');
    b.writeln('  ConfigEntry(${args.join(', ')}),');
  }
  b.writeln('];');
  return b.toString();
}

String emitStress(List<StressEntry> stress, Map<String, Object> constants) {
  final b = StringBuffer(_header);
  b.writeln("import 'types_network.dart';\n");
  b.writeln('// Constants.');
  for (final e in constants.entries) {
    final v = e.value;
    b.writeln('const ${e.key} = ${v is String ? q(v) : v};');
  }
  b.writeln('\n/// Default stress impact/capacity (per RPM) of every block that registers one.');
  b.writeln('const stressDefaults = <StressEntry>[');
  for (final s in stress) {
    final args = <String>[q(s.block)];
    if (s.impact != null) args.add('impact: ${_num(s.impact!)}');
    if (s.capacity != null) args.add('capacity: ${_num(s.capacity!)}');
    if (s.generatedRpm != null) args.add('generatedRpm: ${s.generatedRpm}');
    if (s.mayGenerateLess != null) args.add('mayGenerateLess: ${s.mayGenerateLess}');
    b.writeln('  StressEntry(${args.join(', ')}),');
  }
  b.writeln('];');
  return b.toString();
}

String emitTags(List<TagDef> tags) {
  final b = StringBuffer(_header);
  b.writeln("import 'types_network.dart';\n");
  b.writeln('/// Every tag json under data/*/tags (${tags.length}).');
  b.writeln('const tagDefs = <TagDef>[');
  for (final t in tags) {
    b.writeln('  TagDef(category: ${q(t.category)}, id: ${q(t.id)}${t.replace ? ', replace: true' : ''}, entries: [');
    for (final e in t.entries) {
      final args = <String>[q(e.id)];
      if (e.isTag) args.add('isTag: true');
      if (!e.required) args.add('required: false');
      b.writeln('    TagEntry(${args.join(', ')}),');
    }
    b.writeln('  ]),');
  }
  b.writeln('];');
  return b.toString();
}


String buildReport(NetResult n, ConfigResult c, TagResult t) {
  final b = StringBuffer();
  final sb = n.payloads.where((p) => p.direction == NetDirection.serverbound).toList();
  final cb = n.payloads.where((p) => p.direction == NetDirection.clientbound).toList();
  final create = n.payloads.where((p) => p.id.startsWith('create:')).toList();
  b.writeln('# Network / config / stress / tag extraction report');
  b.writeln();
  b.writeln('Generated by `tool/extract_network_config.dart` (do not hand-edit; rerun the tool).');
  b.writeln();
  b.writeln('## Network payloads');
  b.writeln();
  b.writeln('- Total: **${n.payloads.length}** (serverbound ${sb.length}, clientbound ${cb.length}).');
  b.writeln('- `AllPackets`: ${create.length} (serverbound '
      '${create.where((p) => p.direction == NetDirection.serverbound).length}, clientbound '
      '${create.where((p) => p.direction == NetDirection.clientbound).length}).');
  b.writeln('- Catnip: ${n.payloads.where((p) => p.id.startsWith("catnip:")).length}, '
      'Ponder: ${n.payloads.where((p) => p.id.startsWith("ponder:")).length}.');
  b.writeln('- Payload id = `create:` + lowercase `AllPackets` constant; direction is taken from the '
      '`ClientboundPacketPayload` / `ServerboundPacketPayload` interface found on the class or a superclass '
      '(the section comments in `AllPackets.java` are not used).');
  b.writeln('- Field lists are decoded from each `STREAM_CODEC` (`StreamCodec.composite`, '
      '`CatnipStreamCodecBuilders`, `ByteBufCodecs` combinators, helper methods, referenced class codecs expanded '
      'recursively into `custom` types). Superclass fields (`BlockEntityConfigurationPacket.pos`) are part of the '
      'codec and appear first.');
  b.writeln();
  b.writeln('Wire conventions: `list`/`map` = varint count prefix; `optional` = bool then value; `either` = bool(isLeft) '
      'then the side; `enumeration` = varint ordinal; `direction` = varint data3d; `dispatch` = varint ordinal (or '
      'registry id) then the variant payload; `blockState` = varint id in the block state registry; nullable '
      'values (`CatnipStreamCodecBuilders.nullable`) are `optional` with `nullable: true`.');
  b.writeln();
  final unv = n.payloads.where((p) => !p.verified).toList();
  b.writeln('### Unverified payloads: ${unv.length}');
  if (unv.isEmpty) {
    b.writeln();
    b.writeln('None: every codec was either decoded mechanically or hand verified from the Java `write`/`read` methods.');
  } else {
    for (final p in unv) {
      b.writeln('- `${p.id}` (${p.javaSource}): ${p.note}');
    }
  }
  b.writeln();
  b.writeln('### Hand decoded (override) payloads');
  for (final p in n.payloads.where((p) => p.note != null && p.verified)) {
    b.writeln('- `${p.id}`: ${p.note}');
  }
  b.writeln();
  b.writeln('### Codec quirks worth knowing');
  b.writeln('- `ScheduleEditPacket`: schedule instructions/conditions are `nbtTag` (legacy NBT with registries); their '
      'inner layout is defined by the NBT written in `ScheduleInstruction.write` / `ScheduleWaitCondition.write`.');
  b.writeln('- `MountedStorageSyncPacket`: mounted item/fluid storages are written with `writeWithCodec` as NBT (`nbtTag`).');
  b.writeln('- `registry:` / `idMapper` class names on `varint` fields are registry ids (registration order).');
  b.writeln();
  b.writeln('### Payload list');
  b.writeln();
  b.writeln('| id | dir | fields | verified |');
  b.writeln('|---|---|---|---|');
  for (final p in n.payloads) {
    b.writeln('| `${p.id}` | ${p.direction.name == "serverbound" ? "C2S" : "S2C"} | ${p.fields.length} | ${p.verified ? "yes" : "NO"} |');
  }
  b.writeln();
  b.writeln('## Config defaults');
  b.writeln();
  for (final side in ConfigSide.values) {
    b.writeln('- ${side.name}: ${c.entries.where((e) => e.side == side).length} keys');
  }
  b.writeln('- Total: **${c.entries.length}** (of which ${c.entries.where((e) => e.javaClass == "CStress").length} are '
      'generated stress keys `kinetics.stressValues.v2.{impact,capacity}.<block>`).');
  b.writeln('- Paths are the TOML paths inside `create-<side>.toml` (server = `create-server.toml`), derived by simulating '
      '`ConfigBase.registerAll` (group/nested depth markers push/pop the path stack).');
  b.writeln('- `float` values are stored as the double the Java `float` widens to (`ModConfigSpec` receives a widened '
      'float, e.g. `crankHungerMultiplier` = 0.009999999776482582); unbounded ints use `Integer.MIN/MAX_VALUE`, '
      'unbounded floats use `Float.MAX_VALUE`.');
  b.writeln('- Stress keys are emitted in registration order (the Java map is a hash map, iteration order is unspecified).');
  if (c.log.isNotEmpty) {
    b.writeln();
    b.writeln('Extraction log:');
    for (final l in c.log) {
      b.writeln('- $l');
    }
  }
  b.writeln();
  b.writeln('## Stress table');
  b.writeln();
  b.writeln('- ${c.stress.length} blocks register a default (impact ${c.stress.where((s) => s.impact != null).length}, '
      'capacity ${c.stress.where((s) => s.capacity != null).length}, generator rpm '
      '${c.stress.where((s) => s.generatedRpm != null).length}).');
  b.writeln('- Sources: `.transform(CStress.setImpact/setNoImpact/setCapacity(..))` and '
      '`.onRegister(BlockStressValues.setGeneratorSpeed(..))` in `AllBlocks`, plus the same calls inside the '
      '`BuilderTransformers` methods used by block chains (`encasedBase`, `cuckooClock`, `mechanicalPiston`, `backtank`, ...). '
      'A later call overrides an earlier one (as the Java map does).');
  b.writeln('- Max rotation speed: `kinetics.maxRotationSpeed` default 256 (min 64); `CreativeMotorBlockEntity.MAX_SPEED` = 256.');
  b.writeln();
  b.writeln('## Tags');
  b.writeln();
  final byCat = <String, int>{};
  for (final x in t.tags) {
    byCat['${x.id.split(":").first}/${x.category}'] = (byCat['${x.id.split(":").first}/${x.category}'] ?? 0) + 1;
  }
  b.writeln('- ${t.tags.length} tag files from ${t.fileCount} json files under `src/generated/resources/data/*/tags`.');
  b.writeln('- `replace: true` tags: ${t.tags.where((x) => x.replace).length}; tags with optional entries: '
      '${t.tags.where((x) => x.entries.any((e) => !e.required)).length}.');
  b.writeln('- Entries starting with `#` are kept as references (`isTag: true`).');
  b.writeln();
  b.writeln('| namespace/category | tags |');
  b.writeln('|---|---|');
  for (final e in (byCat.entries.toList()..sort((a, b) => a.key.compareTo(b.key)))) {
    b.writeln('| `${e.key}` | ${e.value} |');
  }
  if (n.log.isNotEmpty) {
    b.writeln();
    b.writeln('## Notes');
    for (final l in n.log) {
      b.writeln('- $l');
    }
  }
  return b.toString();
}
